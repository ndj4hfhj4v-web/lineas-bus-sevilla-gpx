const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const app = fs.readFileSync('src/app.js', 'utf8');
const nav = fs.readFileSync('src/navigation.js', 'utf8');
const ctx = {label: f => f.attributes.LabelLinea};
vm.createContext(ctx);
vm.runInContext(nav.split('\n')[0] + '\n' + app.slice(app.indexOf('function createLineStatistics'), app.indexOf('function renderLineStatistics')), ctx);
const values = new Map();
const storage = () => ({getItem: key => values.get(key), setItem: (key, value) => values.set(key, value)});
const feature = (id, path, sense) => ({attributes:{LabelLinea:id,NombreLinea:'Recorrido '+id,NombreRuta:sense},geometry:{paths:[path]}});
const path = Array.from({length: 5}, (_, i) => [-6 + i * .002, 37.4]);
const outward = feature('05', path, 'Ida'), inward = feature('05', [...path].reverse(), 'Vuelta'), other = feature('10', path, 'Ida');
let time = 0, updates = 0;
const stats = ctx.createLineStatistics(storage, () => updates++);
const visit = (route, point, accuracy = 10) => stats.addPosition(route, {lon:point[0],lat:point[1],accuracy,time:time += 15000});
visit(outward, path[0]);
visit(outward, path[4]);
assert.equal(stats.entries().length, 0, 'Passing the endpoints alone does not count');
for (const point of path.slice(1)) visit(outward, point);
visit(outward, path[4]);
assert.equal(stats.entries()[0][1].count, 1, 'Finishing counts once');
for (const point of [...path].reverse()) visit(inward, point);
for (const point of path) visit(other, point, 100);
assert.equal(stats.entries().length, 2, 'Poor GPS does not count');
for (const point of path) visit(other, point);
for (const point of path) visit(outward, point);
assert.deepEqual(JSON.parse(JSON.stringify(stats.entries().map(([, {line, sense, count}]) => [line,sense,count]))),
 [['05','Ida',2],['05','Vuelta',1],['10','Ida',1]]);
assert.equal(updates, 4);
const persisted = JSON.parse(values.get('copiloter-line-statistics'));
persisted.push(['05',{name:'Recorrido 05',count:3}]);
values.set('copiloter-line-statistics', JSON.stringify(persisted));
const reopened = ctx.createLineStatistics(storage, () => {});
assert.equal(reopened.entries()[0][1].count, 3, 'Legacy counts remain separate');
assert.equal(reopened.entries()[1][1].count, 2, 'Directional counts persist after reopening');
console.log('Correcto: recorridos completos, semivueltas por sentido, GPS impreciso y persistencia.');
