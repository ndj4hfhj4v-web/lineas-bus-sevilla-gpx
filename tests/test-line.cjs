const fs = require('node:fs');
const assert = require('node:assert/strict');
const core = require('../src/core.js');
const original = JSON.parse(fs.readFileSync('src/snapshot.json', 'utf8'));
const previous = [{attributes: {LabelLinea: 'P1'}}, {attributes: {Linea: 'P2'}}];
const cleaned = core.withoutRetiredTestRoutes({...original, features: [...original.features, ...previous]});
assert.deepEqual(cleaned, original);
assert.deepEqual(core.withoutRetiredTestRoutes(cleaned), cleaned);
assert.match(fs.readFileSync('src/app.js', 'utf8'), /data=withoutRetiredTestRoutes\(data\);\s*latestOfflineDataset=data/);
console.log('Correcto: las líneas de prueba antiguas se descartan también de las copias guardadas.');
